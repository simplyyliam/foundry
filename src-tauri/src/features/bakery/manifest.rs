//! `docs/bakery/manifest.md`: what agents read before opening any image.
//! A pure function of the items, so identical state always gives identical bytes.

use super::{file_number, is_unlabeled, BakeryItem};

const UNLABELED: &str = "(unlabeled)";
const NONE: &str = "(none)";

/// One line: runs of whitespace (including newlines) become a single space.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn or(text: String, empty: &str) -> String {
    if text.is_empty() {
        empty.to_string()
    } else {
        text
    }
}

fn list(values: &[String]) -> String {
    let values: Vec<String> = values
        .iter()
        .map(|v| one_line(v))
        .filter(|v| !v.is_empty())
        .collect();
    or(values.join(", "), NONE)
}

pub fn render(items: &[BakeryItem]) -> String {
    let mut sorted: Vec<&BakeryItem> = items.iter().collect();
    sorted.sort_by(|a, b| (file_number(&a.file), &a.file).cmp(&(file_number(&b.file), &b.file)));
    let unlabeled = sorted.iter().filter(|item| is_unlabeled(item)).count();

    let mut out = String::from("# Bakery manifest\n\n");
    out.push_str(
        "<!-- Generated by Foundry from .foundry/bakery.json. Edits here are overwritten. -->\n\n",
    );
    out.push_str(
        "Reference images for this project, in `docs/bakery/`. Read this file first. \
         Open an image only when its entry applies to your task. \
         Entries marked (unlabeled) have no label or no Take note yet: don't act on them.\n\n",
    );
    out.push_str(&format!(
        "{} image(s), {unlabeled} unlabeled.\n",
        sorted.len()
    ));
    for item in sorted {
        out.push_str(&format!("\n## {}\n", item.file));
        out.push_str(&format!(
            "- Label: {}\n",
            or(one_line(&item.label), UNLABELED)
        ));
        out.push_str(&format!(
            "- Take: {}\n",
            or(one_line(&item.take), UNLABELED)
        ));
        out.push_str(&format!("- Skip: {}\n", or(one_line(&item.skip), NONE)));
        out.push_str(&format!("- Tags: {}\n", list(&item.tags)));
        out.push_str(&format!("- Applies to: {}\n", list(&item.applies_to)));
    }
    out
}
